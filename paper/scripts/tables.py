# formatting
# ---------------------------------------------------------------------------------------------
def num(v, d=3, signed=True):
    if v is None:
        return "n/a"
    s = f"{v:+.{d}f}" if signed else f"{v:.{d}f}"
    if s.startswith("-"):
        s = "$-$" + s[1:]
    if signed and s.startswith("+0.000") and d == 3 and abs(v) < 0.0005:
        s = "0.000"
    return s


def ci(iv, d=3):
    if not iv:
        return "n/a"
    return f"[{num(iv['lo'], d)}, {num(iv['hi'], d)}]"


def est(iv, d=3):
    if not iv:
        return "n/a"
    return f"{num(iv['value'], d)} {ci(iv, d)}"


def pct(v, d=1):
    return f"{100 * v:.{d}f}\\%"


def count(n):
    n = int(round(n))
    s = f"{n:,}"
    return s.replace(",", "{,}")


def rate(v, d=2):
    s = f"{v:.{d}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("*", "$\\cdot$")


def form_name(f: str) -> str:
    """A form's name as the paper writes it: nloc_max*D_flow[A,np] -> nloc_max . D_flow (A, np)."""
    f = f.replace("[A,np+ctor]", " (A, non-private, with constructors)")
    f = f.replace("[A,pub+ctor]", " (A, public, with constructors)")
    f = f.replace("[A,np]", " (A, non-private)").replace("[A,pub]", " (A, public)")
    f = f.replace("[B,np+ctor]", " (B, non-private, with constructors)")
    f = f.replace("[B,pub+ctor]", " (B, public, with constructors)")
    f = f.replace("[B,np]", " (B, non-private)").replace("[B,pub]", " (B, public)")
    f = f.replace("[B]", " (B)").replace("[A]", " (A)")
    f = f.replace("@all", " (all calls)").replace("@nohelp", " (no helpers)")
    f = f.replace("|ne", ", fitted on the non-exempt units")
    f = f.replace("&", " $\\cap$ ")
    f = f.replace("*", "$\\cdot$")
    return f.replace("_", "\\_")


MACROS: "OrderedDict[str, str]" = OrderedDict()


def M(name: str, value):
    if not re.fullmatch(r"[A-Za-z]+", name):
        raise ValueError(name)
    if name in MACROS:
        raise ValueError(f"duplicate macro {name}")
    MACROS[name] = str(value)


def write(name: str, body: str):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by paper/scripts/tables.py; do not edit\n" + body)


def cmp_row(c: dict, label: str | None = None) -> str:
    """One row of a paired comparison table: y against x."""
    ax, ay = c["arms"][c["x"]], c["arms"][c["y"]]
    lab = label if label is not None else form_name(c["y"])
    reading = c["reading"].replace("the divergence factor refines complexity", "the form refines complexity")
    return (f"{lab} & {rate(ax['mcc'])} & {rate(ay['mcc'])} & {est(c['micro'])} & "
            f"{rate(ay['precision'])} & {rate(ay['recall'])} & {reading} \\\\")


CMP_HEAD = ("\\begin{tabular}{lrrlrrl}\n\\toprule\n"
            "Form & MCC of X$^*$ & MCC of the form & Paired difference (95\\% CI) & Precision & "
            "Recall & Reading \\\\\n\\midrule\n")
CMP_TAIL = "\\bottomrule\n\\end{tabular}\n"


